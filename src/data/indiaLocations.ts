/**
 * Helper to normalize crop strings across English, Telugu, Hindi, and sub-crop IDs
 */
export function normalizeCropType(filter?: string): string {
  if (!filter) return 'All';
  const f = filter.toLowerCase();
  if (f.includes('tobacco') || f.includes('పొగాకు') || f.includes('तंबाकू') || f === 'tobacco') return 'Tobacco';
  if (f.includes('chilli') || f.includes('mirchi') || f.includes('మిరప') || f.includes('मिर्च') || f === 'chilli') return 'Chilli';
  if (f.includes('paddy') || f.includes('rice') || f.includes('వరి') || f.includes('धान') || f === 'paddy') return 'Paddy';
  if (f.includes('cotton') || f.includes('పత్తి') || f.includes('कपास') || f === 'cotton') return 'Cotton';
  if (f.includes('wheat') || f.includes('గోధుమ') || f.includes('गेहूं') || f === 'wheat') return 'Wheat';
  if (f.includes('maize') || f.includes('corn') || f.includes('మొక్కజొన్న') || f.includes('मक्का') || f === 'maize') return 'Maize';
  if (f.includes('soyabean') || f.includes('soybean') || f.includes('సోయా') || f.includes('सोयाबीन') || f === 'soybean') return 'Soybean';
  if (f.includes('pulse') || f.includes('gram') || f.includes('moong') || f.includes('urad') || f.includes('arhar') || f.includes('tur') || f.includes('chana') || f.includes('दाल') || f.includes('పప్పు') || f === 'pulses') return 'Pulses';
  if (f.includes('mustard') || f.includes('oilseed') || f.includes('सरसों') || f.includes('ఆవాలు') || f === 'mustard') return 'Oilseeds';
  if (f.includes('sugarcane') || f.includes('చెరకు') || f.includes('गन्ना') || f === 'sugarcane') return 'Sugarcane';
  if (f.includes('coconut') || f.includes('copra') || f.includes('కొబ్బరి') || f.includes('കൊപ്ര') || f.includes('नारियल') || f === 'coconut_copra') return 'Coconut';
  if (f.includes('pepper') || f.includes('spices') || f.includes('మిరియాలు') || f.includes('കുരുമുളക്') || f.includes('काली मिर्च') || f === 'black_pepper') return 'Spices';
  if (f.includes('turmeric') || f.includes('పసుపు') || f.includes('हल्दी') || f === 'turmeric') return 'Turmeric';
  return 'All';
}

