/**
 * Checks if a specific time slot has already passed for a given date.
 * If date is in the past, returns true.
 * If date is today, parses the slot start time (e.g. 10:30 AM) and checks if current time has passed it.
 * If date is in the future, returns false.
 */
export function isSlotPassed(slotStr: string, dateString?: string): boolean {
  if (!dateString) return false;
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const todayStr = `${year}-${month}-${day}`;

  if (dateString < todayStr) return true;
  if (dateString > todayStr) return false;

  // Selected date is TODAY: evaluate live running time against slot start
  const match = slotStr.match(/^(\d{1,2}):(\d{2})\s*(AM|PM)/i);
  if (!match) return false;
  let hour = parseInt(match[1], 10);
  const min = parseInt(match[2], 10);
  const period = match[3].toUpperCase();
  if (period === 'PM' && hour < 12) hour += 12;
  if (period === 'AM' && hour === 12) hour = 0;

  const currentMinutes = now.getHours() * 60 + now.getMinutes();
  const slotMinutes = hour * 60 + min;

  return currentMinutes >= slotMinutes;
}

/**
 * Evaluates slot availability for a given Mandi center and date.
 * Deterministic calculation combined with live booked tokens count.
 * Excludes past dates and dynamically expires passed time slots if today is running.
 */
export function getMandiSlotAvailability(
  centerId: string,
  dateString: string,
  bookedTokensForDate: Array<{ scheduledSlot: string; centerId: string }> = []
): {
  mandiStatus: 'OPEN' | 'LIMITED' | 'CLOSED';
  statusMessage: string;
  operatingHours: string;
  slots: SlotAvailabilityInfo[];
} {
  if (!dateString) {
    return {
      mandiStatus: 'LIMITED',
      statusMessage: 'Please select an arrival date to view open time slots.',
      operatingHours: '08:00 AM – 05:30 PM',
      slots: [],
    };
  }

  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const todayStr = `${year}-${month}-${day}`;

  // If selected date is in the past, reject completely
  if (dateString < todayStr) {
    return {
      mandiStatus: 'CLOSED',
      statusMessage: 'Past dates cannot be booked. Please select today or an upcoming date.',
      operatingHours: 'Closed (Past Date)',
      slots: STANDARD_PROCUREMENT_SLOTS.map((slot) => ({
        slot,
        isAvailable: false,
        reason: 'Date has passed',
        remainingCapacity: 0,
        totalCapacity: 0,
      })),
    };
  }

  const dateObj = new Date(dateString);
  const dayOfWeek = isNaN(dateObj.getTime()) ? 1 : dateObj.getDay();

  // Sundays are closed for statutory mandi sanitization and weighbridge calibration
  if (dayOfWeek === 0) {
    return {
      mandiStatus: 'CLOSED',
      statusMessage: 'Mandi is Closed on Sunday for statutory maintenance & weighbridge calibration',
      operatingHours: 'Closed (Sunday)',
      slots: STANDARD_PROCUREMENT_SLOTS.map((slot) => ({
        slot,
        isAvailable: false,
        reason: 'Mandi Closed on Sunday',
        remainingCapacity: 0,
        totalCapacity: 0,
      })),
    };
  }

  // Generate deterministic slot allocations per center & date
  const seedString = `${centerId}_${dateString}`;
  let hash = 0;
  for (let i = 0; i < seedString.length; i++) {
    hash = (hash << 5) - hash + seedString.charCodeAt(i);
    hash |= 0;
  }

  const slotResults: SlotAvailabilityInfo[] = STANDARD_PROCUREMENT_SLOTS.map((slot, idx) => {
    const totalCapacity = 15;

    // Check if slot has already passed for today
    const slotHasPassed = isSlotPassed(slot, dateString);
    if (slotHasPassed) {
      return {
        slot,
        isAvailable: false,
        reason: 'Slot Time Passed Today',
        remainingCapacity: 0,
        totalCapacity,
      };
    }
    
    // Count already booked tokens for this specific center, date, and slot
    const alreadyBooked = bookedTokensForDate.filter(
      (t) => t.scheduledSlot === slot && t.centerId === centerId
    ).length;

    // Simulate baseline occupancy using deterministic pseudo-random hash
    const pseudoBooked = Math.abs((hash + idx * 7) % 8) + alreadyBooked;
    
    // Specifically make 1 or 2 rush slots full or unavailable for realism (e.g. 10:00 AM or 11:30 AM)
    const isRushHourSlot = idx === 4 || idx === 7;
    const forceFull = isRushHourSlot && Math.abs(hash % 3) === 0;

    const currentBooked = forceFull ? totalCapacity : Math.min(totalCapacity, pseudoBooked);
    const remainingCapacity = Math.max(0, totalCapacity - currentBooked);
    const isAvailable = remainingCapacity > 0;

    return {
      slot,
      isAvailable,
      reason: isAvailable ? undefined : 'Slot Full / Not Available',
      remainingCapacity,
      totalCapacity,
    };
  });

  const availableSlotsCount = slotResults.filter((s) => s.isAvailable).length;

  return {
    mandiStatus: availableSlotsCount > 4 ? 'OPEN' : availableSlotsCount > 0 ? 'LIMITED' : 'CLOSED',
    statusMessage:
      availableSlotsCount > 0
        ? `Mandi is OPEN & Accepting Produce (${availableSlotsCount} of ${slotResults.length} Arrival Slots Available)`
        : dateString === todayStr
        ? 'All remaining slots for today have expired or reached capacity'
        : 'All Arrival Slots are Full for this Date at this Center',
    operatingHours: '08:00 AM – 05:30 PM',
    slots: slotResults,
  };
}

